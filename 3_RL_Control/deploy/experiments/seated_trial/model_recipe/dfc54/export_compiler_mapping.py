"""Export the SDK's own allocation script from a successful compiled HAR; no edit."""
import argparse,hashlib,json,os
from pathlib import Path
os.environ.update(CUDA_VISIBLE_DEVICES='',TF_NUM_INTEROP_THREADS='2',TF_NUM_INTRAOP_THREADS='2',OMP_NUM_THREADS='2',OPENBLAS_NUM_THREADS='2')
ap=argparse.ArgumentParser();ap.add_argument('--compilation-result',required=True);a=ap.parse_args()
receipt=Path(a.compilation_result);c=json.loads(receipt.read_text())
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
if not c['compilation_success'] or sha(Path(c['hef_path']))!=c['hef_sha256']:raise RuntimeError('No verified successful HEF')
boundary=c.get('boundary','Conv_205:625')
if boundary not in ('Conv_205:625','Mul_204:624'):raise RuntimeError('Unregistered boundary')
stem='rtmpose_'+boundary.split(':')[0].lower()
har=receipt.parent/(stem+'_research_compiled_model.har')
output=receipt.parent/'autogenerated_allocation.alls';record=receipt.parent/'allocation_export.json'
if output.exists() or record.exists():raise RuntimeError('Refusing overwrite')
from hailo_sdk_client import ClientRunner
runner=ClientRunner(har=str(har),hw_arch='hailo10h')
if hashlib.sha256(runner.hef).hexdigest()!=c['hef_sha256']:raise RuntimeError('Compiled HAR embeds a different HEF')
created=runner.save_autogen_allocation_script(str(output))
report={'public_api':'ClientRunner.save_autogen_allocation_script','source_compilation_receipt_sha256':sha(receipt),
        'source_compiled_har_sha256':sha(har),'source_hef_sha256':c['hef_sha256'],'boundary':boundary,
        'created':bool(created),'script_path':str(output) if created else None,'script_sha256':sha(output) if created else None,
        'no_har_mutation':True,'no_device':True}
record.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
