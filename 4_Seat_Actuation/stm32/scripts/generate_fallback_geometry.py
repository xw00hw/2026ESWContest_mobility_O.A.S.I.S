"""Materialize the exact Experiment A CAD profile as a fallback-only C table.

No serial/probe operations. --check verifies source consistency without edits.
The model-data file and its analysis provenance are owned by experiment_a;
both the host capability check and MCU descriptor hash the same JSON object.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent))
from experiment_a.cad_limits import (
    CAD_CAP_POINTS, CAD_PITCH_MAX_MDEG, CAD_PROFILE, CAD_PROFILE_SHA256,
    CAD_YAW_MAX_MDEG,
)


def artifacts():
    canonical = json.dumps(CAD_PROFILE, sort_keys=True, separators=(',', ':'),
                           ensure_ascii=True, allow_nan=False).encode('utf-8')
    if hashlib.sha256(canonical).hexdigest() != CAD_PROFILE_SHA256:
        raise ValueError('Host CAD profile digest is inconsistent')
    if not 0 < CAD_YAW_MAX_MDEG <= 27000 or not 0 < CAD_PITCH_MAX_MDEG <= 8000:
        raise ValueError('CAD envelope exceeds the existing R8/servo contract')
    points = ', '.join('{'+f'{yaw}, {pitch}'+'}' for yaw, pitch in CAD_CAP_POINTS)
    header = f'''/* Generated by scripts/generate_fallback_geometry.py.
 * Source: experiment_a/cad_profile_data.py canonical JSON, UTF-8 SHA-256.
 * CAD geometry/clearance guard only; NOT a motor load or contact-force rating.
 * Regenerate/check the host and firmware together; never hand widen this table. */
#ifndef FALLBACK_GEOMETRY_PROFILE_H
#define FALLBACK_GEOMETRY_PROFILE_H
#define FALLBACK_CAD_PROFILE_SHA256 "{CAD_PROFILE_SHA256}"
#define FALLBACK_CAD_YAW_MAX_MDEG {CAD_YAW_MAX_MDEG}
#define FALLBACK_CAD_PITCH_MAX_MDEG {CAD_PITCH_MAX_MDEG}
#define FALLBACK_CAD_KNOT_COUNT {len(CAD_CAP_POINTS)}U
#define FALLBACK_CAD_KNOTS {{{points}}}
#endif
'''
    return {
        ROOT/'Core/Inc/fallback_geometry_profile.h': header.encode('utf-8'),
        ROOT/'config/experiment_a_cad_profile.json': canonical+b'\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit('CAD generated artifact differs: '+str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(('Verified' if args.check else 'Generated')+' CAD profile '+CAD_PROFILE_SHA256)


if __name__ == '__main__':
    main()
